// Writes db/blogs-seed.sql: creates the `blogs` table and inserts the old
// site's posts (src/data/blogs.json). Run that SQL on the live database
// (phpMyAdmin → Import, or `mysql ... < db/blogs-seed.sql`).
// INSERT IGNORE skips posts whose slug already exists, so it is safe to re-run.
// Usage: node scripts/export-blogs-sql.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import mysql from "mysql2";

const PROJECT_DIR = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const posts = JSON.parse(fs.readFileSync(path.join(PROJECT_DIR, "src/data/blogs.json"), "utf8"));

const schema = fs.readFileSync(path.join(PROJECT_DIR, "db/schema.sql"), "utf8");
const createBlogs = schema.slice(schema.indexOf("CREATE TABLE IF NOT EXISTS `blogs`"));

const lines = [
  "-- Articles / Blogs: table + the old site's posts. Generated by scripts/export-blogs-sql.mjs.",
  "SET NAMES utf8mb4;",
  "",
  createBlogs.trim(),
  "",
];

for (const p of [...posts].reverse()) {
  lines.push(
    mysql.format(
      "INSERT IGNORE INTO `blogs` (slug, title, excerpt, content, seo_title, meta_description, image_url, published_date, is_published) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1);",
      [p.slug, p.title, p.excerpt, p.html, p.seoTitle, p.metaDescription, p.image, p.date],
    ),
  );
}

const out = path.join(PROJECT_DIR, "db/blogs-seed.sql");
fs.writeFileSync(out, lines.join("\n") + "\n", "utf8");
console.log(`Wrote ${posts.length} posts to ${path.relative(PROJECT_DIR, out)}`);
